#!/usr/bin/env python3
"""Generates crates/ss-app/THIRD_PARTY_LICENSES.md from `cargo metadata`.

Lists every external crate the app links on any platform (macOS, Windows, other), with licence
expression and repository, followed by the licence/notice files shipped in the crates (identical
texts are printed once with all crates that use them). The app shows this file on its About page.

    python3 scripts/third_party_licenses.py           # (re)write the file
    python3 scripts/third_party_licenses.py --check   # exit 1 if the file is out of date (CI)

Needs the crate sources locally (`cargo fetch` or any build).
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates" / "ss-app" / "THIRD_PARTY_LICENSES.md"
APP_CRATE = "ss-app"
LICENSE_FILE = re.compile(
    r"^((LICEN[CS]E|COPYING|NOTICES?|UNLICENSE)([-._].*)?"  # LICENSE-MIT, NOTICES.md, …
    r"|(OFL|UFL)\.txt"  # font licences (egui's bundled fonts)
    r"|[\w.-]*licen[cs]e[\w.-]*\.(txt|md))$",  # e.g. emoji-icon-font-mit-license.txt
    re.IGNORECASE,
)
# Licence texts in files whose names do not say so: {crate: [path inside the crate]}.
EXTRA_LICENSE_FILES = {
    "epaint_default_fonts": ["fonts/Hack-Regular.txt"],  # Hack font licence (MIT + Bitstream Vera)
}
# Subdirectories that may hold licences of bundled C code (e.g. hidapi's etc/hidapi).
MAX_DEPTH = 3
SKIP_DIRS = {"target", "tests", "test", "examples", "benches", ".git", "fuzz"}


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def app_dependencies(meta):
    """External packages reachable from the app crate (all platforms, normal + build deps)."""
    workspace = set(meta["workspace_members"])
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    app = next(i for i in workspace if packages[i]["name"] == APP_CRATE)
    seen, stack = set(), [app]
    while stack:
        for dep in nodes[stack.pop()]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds == {"dev"} or dep["pkg"] in seen:
                continue
            seen.add(dep["pkg"])
            stack.append(dep["pkg"])
    deps = [packages[i] for i in seen if i not in workspace]
    return sorted(deps, key=lambda p: (p["name"].lower(), p["version"]))


def license_files(package_dir, depth=0):
    found = []
    # Sort by name explicitly: Path ordering is case-insensitive on Windows but not on macOS, and
    # the output must be identical on every OS (CI checks it on Windows).
    for entry in sorted(package_dir.iterdir(), key=lambda e: e.name):
        if entry.is_file() and LICENSE_FILE.match(entry.name):
            found.append(entry)
        elif entry.is_dir() and depth < MAX_DEPTH and entry.name not in SKIP_DIRS:
            found.extend(license_files(entry, depth + 1))
    return found


def render(deps):
    lines = [
        "# Third-party licences",
        "",
        "OpenSeries is MIT OR Apache-2.0. It includes the following open-source crates",
        "(all platforms; generated by `scripts/third_party_licenses.py`, do not edit), plus the",
        "Rust standard library (MIT OR Apache-2.0, https://github.com/rust-lang/rust; same licence",
        "texts as OpenSeries itself).",
        "",
        "| Crate | Version | Licence | Source |",
        "|---|---|---|---|",
    ]
    texts = {}  # licence text -> list of "name version"
    for p in deps:
        lines.append(
            f"| {p['name']} | {p['version']} | {p.get('license') or p.get('license_file') or '?'} "
            f"| {p.get('repository') or 'crates.io'} |"
        )
        package_dir = pathlib.Path(p["manifest_path"]).parent
        extra = [package_dir / name for name in EXTRA_LICENSE_FILES.get(p["name"], [])]
        for path in license_files(package_dir) + extra:
            text = path.read_text(encoding="utf-8", errors="replace").strip()
            if text:
                texts.setdefault(text, []).append(f"{p['name']} {p['version']}")
    lines += ["", "## Licence texts", ""]
    for text, users in sorted(texts.items(), key=lambda item: (item[1][0].lower(), item[0])):
        unique = sorted(set(users), key=str.lower)
        lines += [f"### Used by: {', '.join(unique)}", "", "```text", text, "```", ""]
    return "\n".join(lines).rstrip() + "\n"


def main():
    content = render(app_dependencies(metadata()))
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/third_party_licenses.py")
            for number, (old, new) in enumerate(zip(current.splitlines(), content.splitlines()), 1):
                if old != new:
                    print(f"first difference at line {number}:\n  file:      {old!r}\n  generated: {new!r}")
                    break
            else:
                print(f"length differs: file {len(current)} chars, generated {len(content)}")
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")  # LF on every OS
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(content) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
